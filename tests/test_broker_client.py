"""Test dell'adapter LLM del broker."""

from __future__ import annotations

from types import SimpleNamespace

import pytest

from core.broker import BrokerError
from core.models import ModelConfig
from core.task_profile import TaskProfile, TaskProfileStore
from core.timeouts import TimeoutPolicy
from llm.broker_client import BrokerLLMClient


class FakeAudit:
    def __init__(self):
        self.events = []

    def record(self, event, **fields):
        self.events.append((event, fields))


class FakeLLM:
    provider = "lmstudio"
    supports_native_tools = True

    def __init__(self, model):
        self.model = model
        self.native_tools = True
        self.timeout = 120
        self.last_usage = "usage"
        self.last_reasoning = "reasoning"
        self.usage_sink = None
        self.calls = []

    def chat(self, messages):
        self.calls.append(("chat", messages))
        return f"answer from {self.model}"

    def generate(self, prompt, system_prompt=None):
        self.calls.append(("generate", prompt, system_prompt))
        return f"generated by {self.model}"

    def request_tool_call(self, messages, registry):
        self.calls.append(("request_tool_call", messages, registry))
        return "tool-call"

    def native_step(self, messages, registry):
        self.calls.append(("native_step", messages, registry))
        return "native"

    def _native_request(self, messages, registry):
        self.calls.append(("native_request", messages, registry))
        return "native-request"


class FakeBroker:
    def __init__(self, entry=None, error=None):
        self.entry = entry or SimpleNamespace(
            id="lmstudio/coder",
            provider="lmstudio",
            model="coder",
        )
        self.error = error

    def select(self, profile):
        if self.error is not None:
            raise self.error
        return SimpleNamespace(
            entry=self.entry,
            score=0.8123,
        )


def make_client(broker, factory, audit=None):
    return BrokerLLMClient(
        broker,
        ModelConfig(provider="lmstudio", name="base"),
        profile="coding",
        audit=audit,
        llm_factory=factory,
    )


def test_uses_selected_model_and_audits():
    audit = FakeAudit()
    created = []

    def factory(config, audit=None):
        client = FakeLLM(config.name)
        created.append((config, client))
        return client

    client = make_client(FakeBroker(), factory, audit)

    assert client.provider == "lmstudio"
    assert client.model == "coder"
    assert client.chat([{"role": "user", "content": "hi"}]) == "answer from coder"
    assert created[0][0].name == "coder"
    assert created[0][0].provider == "lmstudio"
    assert any(event == "broker.decision" for event, _ in audit.events)


def test_delegates_native_tools_and_usage():
    def factory(config, audit=None):
        return FakeLLM(config.name)

    client = make_client(FakeBroker(), factory)
    client.native_tools = False
    client.usage_sink = "sink"

    assert client.native_tools is False
    assert client.usage_sink == "sink"
    assert client.last_usage == "usage"
    assert client.last_reasoning == "reasoning"
    assert client.native_step([], object()) == "native"
    assert client.request_tool_call([], object()) == "tool-call"


def test_falls_back_when_no_model_is_eligible():
    audit = FakeAudit()
    created = []

    def factory(config, audit=None):
        client = FakeLLM(config.name)
        created.append(config.name)
        return client

    broker = FakeBroker(
        error=BrokerError(
            "no eligible model",
            excluded=[{"model_id": "x", "reasons": ["nope"]}],
        )
    )
    client = make_client(broker, factory, audit)

    assert client.model == "base"
    assert client.selection is None
    assert "no eligible" in client.fallback_reason
    assert created == ["base"]
    assert any(event == "broker.fallback" for event, _ in audit.events)


def test_falls_back_when_selected_client_fails():
    audit = FakeAudit()
    attempts = []

    def factory(config, audit=None):
        attempts.append(config.name)

        if config.name == "coder":
            raise RuntimeError("provider down")

        return FakeLLM(config.name)

    client = make_client(FakeBroker(), factory, audit)

    assert client.model == "base"
    assert client.selection is None
    assert "provider down" in client.fallback_reason
    assert attempts == ["coder", "base"]
    assert any(event == "broker.fallback" for event, _ in audit.events)


def test_strict_loaded_mode_does_not_fallback():
    broker = FakeBroker(
        error=BrokerError(
            "no eligible model",
            excluded=[{"model_id": "x", "reasons": ["model not loaded"]}],
        )
    )

    def factory(config, audit=None):
        return FakeLLM(config.name)

    with pytest.raises(BrokerError):
        BrokerLLMClient(
            broker,
            ModelConfig(provider="lmstudio", name="base"),
            profile="coding",
            llm_factory=factory,
            allow_fallback=False,
        )


def test_missing_audit_is_allowed():
    def factory(config, audit=None):
        return FakeLLM(config.name)

    client = make_client(FakeBroker(), factory, audit=None)

    assert client.model == "coder"


def test_adaptive_timeout_is_applied():
    entry = SimpleNamespace(
        id="lmstudio/slow",
        provider="lmstudio",
        model="slow",
        card={
            "benchmarks": {
                "chat": {
                    "duration_ms": {
                        "p50": 50000,
                        "p95": 100000,
                    }
                }
            }
        },
    )

    def factory(config, audit=None):
        return FakeLLM(config.name)

    client = BrokerLLMClient(
        FakeBroker(entry),
        ModelConfig(provider="lmstudio", name="base"),
        profile="coding",
        llm_factory=factory,
        timeout_policy=TimeoutPolicy(
            floor_seconds=30,
            ceiling_seconds=900,
        ),
    )

    client.chat([{"role": "user", "content": "x"}])

    assert client._client.timeout >= 30
    assert client.turn_timeout is not None


def test_local_only_forces_local_privacy():
    seen = []

    class LocalBroker:
        profiles = TaskProfileStore([
            TaskProfile(name="coding", privacy="any"),
        ])

        def select(self, profile):
            seen.append(profile)
            return SimpleNamespace(
                entry=SimpleNamespace(
                    id="lmstudio/local",
                    provider="lmstudio",
                    model="local",
                ),
                score=0.8,
            )

    def factory(config, audit=None):
        return FakeLLM(config.name)

    client = BrokerLLMClient(
        LocalBroker(),
        ModelConfig(provider="lmstudio", name="base"),
        profile="coding",
        llm_factory=factory,
        local_only=True,
    )

    assert client.model == "local"
    assert seen[0].privacy == "local_only"


def test_switch_profile_replaces_client():
    audit = FakeAudit()
    broker = FakeBroker()
    created = []

    def factory(config, audit=None):
        client = FakeLLM(config.name)
        created.append(config.name)
        return client

    client = make_client(broker, factory, audit)
    broker.entry = SimpleNamespace(
        id="lmstudio/quality",
        provider="lmstudio",
        model="quality",
    )

    selection = client.switch_profile("quality_chat")

    assert selection.entry.id == "lmstudio/quality"
    assert client.profile == "quality_chat"
    assert client.model == "quality"
    assert created == ["coder", "quality"]
    assert any(
        event == "broker.decision"
        and fields.get("action") == "switch"
        for event, fields in audit.events
    )


def test_switch_profile_failure_keeps_old_client():
    audit = FakeAudit()
    broker = FakeBroker()
    created = []

    def factory(config, audit=None):
        if config.name == "quality":
            raise RuntimeError("quality unavailable")
        client = FakeLLM(config.name)
        created.append(config.name)
        return client

    client = make_client(broker, factory, audit)
    broker.entry = SimpleNamespace(
        id="lmstudio/quality",
        provider="lmstudio",
        model="quality",
    )

    try:
        client.switch_profile("quality_chat")
    except RuntimeError:
        pass
    else:
        raise AssertionError("switch should fail")

    assert client.profile == "coding"
    assert client.model == "coder"
    assert created == ["coder"]
    assert any(
        event == "broker.switch_failed"
        for event, _ in audit.events
    )
